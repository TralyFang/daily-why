def flatten():
    items = []
    seen = set()
    dups = []
    for topic, titles in TOPICS.items():
        for title in titles:
            title = title.strip()
            if not title.endswith("？"):
                raise SystemExit(f"Title must end with ？: {title}")
            if not title.startswith("为什么"):
                raise SystemExit(f"Title must start with 为什么: {title}")
            key = title.replace(" ", "")
            if key in seen:
                dups.append(title)
                continue
            seen.add(key)
            items.append({"title": title, "topic": topic})
    if dups:
        raise SystemExit(f"Duplicate titles: {dups}")
    return items


def main():
    items = flatten()
    if len(items) < 1000:
        raise SystemExit(f"Need 1000+ questions, got {len(items)}")

    # Fix accidental English leftover if any
    for item in items:
        if any(ord(ch) < 128 and ch.isalpha() for ch in item["title"]):
            # allow none; titles should be Chinese. Check mixed English words
            if any(word.isascii() and word.isalpha() and len(word) > 2 for word in item["title"].replace("？", "").split()):
                raise SystemExit(f"English in title: {item['title']}")

    out = Path(__file__).resolve().parents[1] / "src" / "lib" / "questionBankData.ts"
    lines = [
        "export interface BankQuestion {",
        "  title: string;",
        "  topic: string;",
        "}",
        "",
        "export const QUESTION_BANK: BankQuestion[] = [",
    ]
    for item in items:
        title = item["title"].replace("\\", "\\\\").replace('"', '\\"')
        topic = item["topic"].replace("\\", "\\\\").replace('"', '\\"')
        lines.append(f'  {{ title: "{title}", topic: "{topic}" }},')
    lines.append("];")
    lines.append("")
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {len(items)} questions to {out}")
    counts = {}
    for item in items:
        counts[item["topic"]] = counts.get(item["topic"], 0) + 1
    for topic, n in counts.items():
        print(f"  {topic}: {n}")


if __name__ == "__main__":
    main()
